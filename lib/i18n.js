export const LANGS = ['en', 'el'];
let lang = 'en';

/** Greek when the browser is in Greek, otherwise English. */
export const defaultLang = () => (/^el\b/i.test(navigator.language || '') ? 'el' : 'en');

export function setLang(code) {
  lang = LANGS.includes(code) ? code : 'en';
  document.documentElement.lang = lang;
}
export const getLang = () => lang;

export function t(key, vars = {}) {
  const v = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (typeof v === 'function') return v(vars);
  return String(v).replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
}

export function count(n, noun) {
  const forms = STRINGS[lang][noun] || STRINGS.en[noun];
  return `${n} ${n === 1 ? forms[0] : forms[1]}`;
}

/** Fill the static page text: data-i18n (text), data-i18n-html, data-i18n-title, data-i18n-aria. */
export function applyStatic(root) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n, el.dataset.i18nN ? { n: el.dataset.i18nN } : {});
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
}
